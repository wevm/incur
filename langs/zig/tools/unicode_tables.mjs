// Generates `src/unicode.zig` from the running Node's Unicode data, the case mappings and
// properties JavaScript's `toLowerCase` and case-insensitive regular expressions use:
//
//   node tools/unicode_tables.mjs > src/unicode.zig && zig fmt src/unicode.zig

/** Compresses `[cp, mapped]` pairs into runs with a constant delta and a stride of 1 or 2. */
function mappingRuns(pairs) {
  const runs = []
  for (const [cp, mapped] of pairs) {
    const delta = mapped - cp
    const run = runs.at(-1)
    if (run && run.delta === delta) {
      const stride = run.last === run.first ? cp - run.last : run.stride
      if ((stride === 1 || stride === 2) && cp - run.last === stride) {
        run.stride = stride
        run.last = cp
        continue
      }
    }
    runs.push({ first: cp, last: cp, delta, stride: 1 })
  }
  return runs
}

/** Compresses the code points matching `regex` into inclusive ranges. */
function propertyRanges(regex) {
  const ranges = []
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (!regex.test(String.fromCodePoint(cp))) continue
    const range = ranges.at(-1)
    if (range && range[1] === cp - 1) range[1] = cp
    else ranges.push([cp, cp])
  }
  return ranges
}

const hex = (n) => `0x${n.toString(16)}`

const lower = []
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue
  const mapped = [...String.fromCodePoint(cp).toLowerCase()]
  if (mapped.length === 1 && mapped[0].codePointAt(0) !== cp)
    lower.push([cp, mapped[0].codePointAt(0)])
}

// `Canonicalize` of ECMAScript regular expressions without the `u` flag: a code unit maps to its
// uppercase form when that is one code unit and does not turn a non-ASCII unit into ASCII.
const canonical = []
for (let cu = 0; cu <= 0xffff; cu++) {
  const upper = String.fromCharCode(cu).toUpperCase()
  if (upper.length !== 1) continue
  const mapped = upper.charCodeAt(0)
  if (mapped === cu || (cu >= 128 && mapped < 128)) continue
  canonical.push([cu, mapped])
}

const runs = (name, doc, pairs) =>
  `/// ${doc}\nconst ${name} = [_]Run{\n${mappingRuns(pairs)
    .map(
      (r) =>
        `    .{ .first = ${hex(r.first)}, .last = ${hex(r.last)}, .delta = ${r.delta}, .stride = ${r.stride} },`,
    )
    .join('\n')}\n};\n`
const ranges = (name, doc, regex) =>
  `/// ${doc}\nconst ${name} = [_]Range{\n${propertyRanges(regex)
    .map(([first, last]) => `    .{ ${hex(first)}, ${hex(last)} },`)
    .join('\n')}\n};\n`

process.stdout
  .write(`//! Unicode ${process.versions.unicode} case data, generated by \`tools/unicode_tables.mjs\` from Node's
//! \`String.prototype.toLowerCase\`, \`toUpperCase\`, and \`\\p{Cased}\` and \`\\p{Case_Ignorable}\`.
//! Do not edit by hand.

/// Code points \`first..last\`, every \`stride\`th one, map to themselves plus \`delta\`.
const Run = struct { first: u21, last: u21, delta: i32, stride: u2 };

/// An inclusive code point range.
const Range = struct { u21, u21 };

${runs('lower_runs', 'Single code point results of `toLowerCase`.', lower)}
${runs('canonical_runs', 'Code units that case-insensitive regular expressions without the `u` flag fold to another unit.', canonical)}
${ranges('cased', 'Code points with the `Cased` property.', /\p{Cased}/u)}
${ranges('case_ignorable', 'Code points with the `Case_Ignorable` property.', /\p{Case_Ignorable}/u)}
/// Returns the mapping of \`cp\` in \`table\`, or \`cp\` itself.
fn map(table: []const Run, cp: u21) u21 {
    var low: usize = 0;
    var high = table.len;
    while (low < high) {
        const mid = (low + high) / 2;
        const run = table[mid];
        if (cp < run.first) {
            high = mid;
        } else if (cp > run.last) {
            low = mid + 1;
        } else {
            if ((cp - run.first) % run.stride != 0) return cp;
            return @intCast(@as(i32, cp) + run.delta);
        }
    }
    return cp;
}

/// Whether \`cp\` lies in one of the sorted \`ranges\`.
fn within(ranges: []const Range, cp: u21) bool {
    var low: usize = 0;
    var high = ranges.len;
    while (low < high) {
        const mid = (low + high) / 2;
        if (cp < ranges[mid][0]) {
            high = mid;
        } else if (cp > ranges[mid][1]) {
            low = mid + 1;
        } else return true;
    }
    return false;
}

/// Returns the lowercase form of a code point when \`toLowerCase\` maps it to one code point.
pub fn lower(cp: u21) u21 {
    return map(&lower_runs, cp);
}

/// Folds a UTF-16 code unit as a case-insensitive regular expression without the \`u\` flag does.
pub fn canonicalize(cp: u21) u21 {
    return if (cp > 0xffff) cp else map(&canonical_runs, cp);
}

/// Whether a code point is cased, as the final sigma rule of \`toLowerCase\` tests.
pub fn isCased(cp: u21) bool {
    return within(&cased, cp);
}

/// Whether a code point is case-ignorable, as the final sigma rule of \`toLowerCase\` tests.
pub fn isCaseIgnorable(cp: u21) bool {
    return within(&case_ignorable, cp);
}
`)
